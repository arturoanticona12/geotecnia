def dx(s, p, target):
    for i in range(len(s) - 1):
        if p[i + 1] <= target <= p[i] and p[i] != p[i + 1]:
            return 10 ** (math.log10(s[i + 1]) + (target - p[i + 1]) / (p[i] - p[i + 1]) * (math.log10(s[i]) - math.log10(s[i + 1])))
    return None


